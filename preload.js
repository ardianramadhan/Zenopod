  onQuickState: on('kapsul:quick-state'),
  onTyping: on('kapsul:typing'),
  onLocks: on('kapsul:locks'),
  pet: (action, food) => ipcRenderer.send('kapsul:pet', action, food),
  drink: () => ipcRenderer.send('kapsul:drink'),
  waterSettings: (patch) => ipcRenderer.send('kapsul:water-settings', patch),
  onPetEvent: on('kapsul:pet-event'),
  quick: (query) => ipcRenderer.invoke('kapsul:quick', query),
  copy: (text) => ipcRenderer.send('kapsul:copy', text),
  timer: (action, payload) => ipcRenderer.send('kapsul:timer', action, payload),
  onTimers: on('kapsul:timers'),
  onCalendar: on('kapsul:calendar'),
  meeting: (url) => ipcRenderer.send('kapsul:meeting', url),
  onSystem: on('kapsul:system'),
  onHabits: on('kapsul:habits'),
  habit: (id, done) => ipcRenderer.send('kapsul:habit', id, done),
  snip: () => ipcRenderer.send('kapsul:snip'),
  onState: on('kapsul:state'),
  onMedia: on('kapsul:media'),
  onLyrics: on('kapsul:lyrics'),
  onDevice: on('kapsul:device'),
  onDevices: on('kapsul:devices'),
  onLive: on('kapsul:live'),
  onScreen: on('kapsul:screen'),
  photos: () => ipcRenderer.invoke('kapsul:photos'),
  wallpapers: () => ipcRenderer.invoke('kapsul:wallpapers'),
  wallpaperAdd: (dataUrl) => ipcRenderer.invoke('kapsul:wallpaper-add', dataUrl),
  wallpaperPick: () => ipcRenderer.invoke('kapsul:wallpaper-pick'),
  wallpaperSlideshow: (minutes, shuffle) => ipcRenderer.invoke('kapsul:wallpaper-slideshow', minutes, shuffle),
  onWallpapers: on('kapsul:wallpaper-state'),
