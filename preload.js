'use strict';

const { contextBridge, ipcRenderer, webUtils } = require('electron');

const on = (channel) => (callback) => ipcRenderer.on(channel, (_event, payload) => callback(payload));

contextBridge.exposeInMainWorld('kapsul', {
  ready: () => ipcRenderer.send('kapsul:ready'),
  expand: (next, focus = false) => ipcRenderer.send('kapsul:expand', next, focus),
  pin: (on) => ipcRenderer.send('kapsul:pin', on),
  onPinned: on('kapsul:pinned'),
  launch: (index) => ipcRenderer.send('kapsul:launch', index),
  media: (command) => ipcRenderer.send('kapsul:media', command),
  seek: (ms) => ipcRenderer.send('kapsul:seek', ms),
  openSettings: (section) => ipcRenderer.send('kapsul:settings', section),
  setPosition: (position) => ipcRenderer.send('kapsul:position', position),
  dragStart: () => ipcRenderer.send('kapsul:drag-start'),
  dragMove: (dx, dy) => ipcRenderer.send('kapsul:drag-move', dx, dy),
  dragEnd: () => ipcRenderer.send('kapsul:drag-end'),
  power: (action) => ipcRenderer.send('kapsul:power', action),
  installedApps: () => ipcRenderer.invoke('kapsul:installed'),
  launchInstalled: (key) => ipcRenderer.send('kapsul:launch-installed', key),
  openNotification: (id) => ipcRenderer.send('kapsul:notif-open', id),
  dismissNotification: (id) => ipcRenderer.send('kapsul:notif-dismiss', id),
  clearNotifications: () => ipcRenderer.send('kapsul:notif-clear'),
  peekAction: (id, action) => ipcRenderer.send('kapsul:peek-action', id, action),
  peekClick: (id) => ipcRenderer.send('kapsul:peek-click', id),
  focus: (action, minutes) => ipcRenderer.send('kapsul:focus', action, minutes),
  onFocus: on('kapsul:focus'),
  clip: (action, id) => ipcRenderer.send('kapsul:clip', action, id),
  todo: (action, payload) => ipcRenderer.send('kapsul:todo', action, payload),
  onClips: on('kapsul:clips'),
  devOpen: (kind, index) => ipcRenderer.send('kapsul:dev-open', kind, index),
  devRefresh: () => ipcRenderer.send('kapsul:dev-refresh'),
  onDev: on('kapsul:dev'),
  battery: (state) => ipcRenderer.send('kapsul:battery', state),
  onWeather: on('kapsul:weather'),
  onCostume: on('kapsul:costume'),
  sendAudio: (wav, mode) => ipcRenderer.invoke('kapsul:audio', wav, mode),
  chatSend: (text, files, options) => ipcRenderer.invoke('kapsul:chat-send', text, files, options),
  chatReset: () => ipcRenderer.send('kapsul:chat-reset'),
  onChat: on('kapsul:chat'),
  onListen: on('kapsul:listen'),
  onSpeech: on('kapsul:speech'),
  onTodos: on('kapsul:todos'),
  onStats: on('kapsul:stats'),
  ask: (question) => ipcRenderer.invoke('kapsul:ask', question),
  quickSet: (what, value) => ipcRenderer.send('kapsul:quick-set', what, value),
  onQuickState: on('kapsul:quick-state'),
  onTyping: on('kapsul:typing'),
  onLocks: on('kapsul:locks'),
  pet: (action, food) => ipcRenderer.send('kapsul:pet', action, food),
  drink: () => ipcRenderer.send('kapsul:drink'),
  ytInfo: (id) => ipcRenderer.invoke('kapsul:yt-info', id),
  ytOpen: (id, seconds) => ipcRenderer.send('kapsul:yt-open', id, seconds),
  theater: (on) => ipcRenderer.send('kapsul:theater', on),
  theaterResize: (phase, dx) => ipcRenderer.send('kapsul:theater-resize', phase, dx),
  theaterMove: (phase, dx, dy, moved) => ipcRenderer.send('kapsul:theater-move', phase, dx, dy, moved),
  onTheater: on('kapsul:theater'),
  onPrayer: on('kapsul:prayer'),
  onNet: on('kapsul:net'),
  onPresenting: on('kapsul:presenting'),
  onShelf: on('kapsul:shelf'),
  // Path file yang dilepas ke island (File.path sudah tidak ada sejak Electron 32).
  filePaths: (files) => files.map((file) => webUtils.getPathForFile(file)).filter(Boolean),
  shelfAdd: (paths) => ipcRenderer.send('kapsul:shelf-add', paths),
  shelfRemove: (ids) => ipcRenderer.send('kapsul:shelf-remove', ids),
  shelfClear: () => ipcRenderer.send('kapsul:shelf-clear'),
  shelfOpen: (id) => ipcRenderer.send('kapsul:shelf-open', id),
  shelfReveal: (id) => ipcRenderer.send('kapsul:shelf-reveal', id),
  shelfDrag: (ids) => ipcRenderer.send('kapsul:shelf-drag', ids),
  waterSettings: (patch) => ipcRenderer.send('kapsul:water-settings', patch),
  onPetEvent: on('kapsul:pet-event'),
  quick: (query) => ipcRenderer.invoke('kapsul:quick', query),
  copy: (text) => ipcRenderer.send('kapsul:copy', text),
  timer: (action, payload) => ipcRenderer.send('kapsul:timer', action, payload),
  onTimers: on('kapsul:timers'),
  onCalendar: on('kapsul:calendar'),
  meeting: (url) => ipcRenderer.send('kapsul:meeting', url),
  onSystem: on('kapsul:system'),
  onHabits: on('kapsul:habits'),
  habit: (id, done) => ipcRenderer.send('kapsul:habit', id, done),
  snip: () => ipcRenderer.send('kapsul:snip'),
  onState: on('kapsul:state'),
  onMedia: on('kapsul:media'),
  onLyrics: on('kapsul:lyrics'),
  onDevice: on('kapsul:device'),
  onDevices: on('kapsul:devices'),
  onLive: on('kapsul:live'),
  onScreen: on('kapsul:screen'),
  wallpaperAdd: (dataUrl) => ipcRenderer.invoke('kapsul:wallpaper-add', dataUrl),
  micMute: (muted) => ipcRenderer.send('kapsul:mic-mute', muted),
  detail: (value) => ipcRenderer.send('kapsul:detail', Boolean(value)),
  openDrive: (letter) => ipcRenderer.send('kapsul:drive', 'open', letter),
  ejectDrive: (letter) => ipcRenderer.send('kapsul:drive', 'eject', letter),
  onIslandPreview: on('kapsul:island-preview'),
  onCursor: on('kapsul:cursor'),
  onExpanded: on('kapsul:expanded'),
  onNotifications: on('kapsul:notifications'),
  onPeek: on('kapsul:peek'),
  onClaude: on('kapsul:claude'),
  onReminders: on('kapsul:reminders'),
});
